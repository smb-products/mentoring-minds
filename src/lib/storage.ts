import 'server-only';
import { createHmac, timingSafeEqual } from 'node:crypto';
import { mkdir, open, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { del, get, head } from '@vercel/blob';

/**
 * File storage. Two drivers with the same functions:
 *   - Vercel Blob (production): a PRIVATE store. The browser uploads straight to Blob
 *     (client upload, token from /api/files/blob), so big PDFs never pass through a
 *     function (Vercel caps request bodies at 4.5 MB). Downloads stream through
 *     /api/files/[id] after a permission check — private blobs have no public URL.
 *   - local (development and tests): files under ./uploads; uploads go to
 *     /api/files/upload/[id].
 *
 * Blob is used whenever BLOB_READ_WRITE_TOKEN is set (Vercel adds it when you connect
 * the store with "Add a read-write token"). In production without it, uploads fail
 * with a clear error instead of writing to a disk that Vercel throws away.
 */

const UPLOAD_TTL_SEC = 10 * 60;

export const ALLOWED_TYPES = ['application/pdf', 'image/png', 'image/jpeg', 'image/webp'] as const;
export type AllowedType = (typeof ALLOWED_TYPES)[number];
export const MAX_BYTES = 25 * 1024 * 1024;

export const usingBlob = () => Boolean(process.env.BLOB_READ_WRITE_TOKEN);

const EXT: Record<AllowedType, string> = { 'application/pdf': 'pdf', 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp' };

/** Storage keys are random and never derived from the file's own name. */
export const storageKeyFor = (token: string, mimeType: AllowedType) => `files/${token}.${EXT[mimeType]}`;

/* ── local driver ───────────────────────────────────────── */

const LOCAL_ROOT = () => path.join(process.cwd(), 'uploads');
/** Keys are generated by the server; this only guards against mistakes. */
const localPath = (key: string) => {
  const clean = key.replace(/[^a-zA-Z0-9_\-/.]/g, '').replace(/\.\.+/g, '.');
  const full = path.join(LOCAL_ROOT(), clean);
  if (!full.startsWith(LOCAL_ROOT() + path.sep)) throw new Error('Bad storage key');
  return full;
};

const secret = () => {
  const s = process.env.AUTH_SECRET;
  if (!s) throw new Error('AUTH_SECRET is not set.');
  return s;
};

/** Signed token for a local upload URL: `<expiresAtSec>.<hmac>`. */
export function localUploadToken(fileId: string, now = Date.now()) {
  const exp = Math.floor(now / 1000) + UPLOAD_TTL_SEC;
  return `${exp}.${createHmac('sha256', secret()).update(`upload:${fileId}:${exp}`).digest('base64url')}`;
}

export function checkLocalUploadToken(fileId: string, token: string | null, now = Date.now()) {
  const [expStr, mac] = (token ?? '').split('.');
  const exp = Number(expStr);
  if (!exp || !mac || exp * 1000 < now) return false;
  const want = createHmac('sha256', secret()).update(`upload:${fileId}:${exp}`).digest();
  const got = Buffer.from(mac, 'base64url');
  return got.length === want.length && timingSafeEqual(got, want);
}

/** Local driver only: the upload route writes the bytes here. */
export async function writeLocal(key: string, bytes: Uint8Array) {
  const file = localPath(key);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, bytes);
}

export const readLocal = (key: string) => readFile(localPath(key));

/* ── API used by the server functions and routes ────────── */

export type UploadTarget =
  | { kind: 'blob'; pathname: string; handleUploadUrl: string; clientPayload: string; contentType: AllowedType }
  | { kind: 'local'; url: string; method: 'PUT'; headers: Record<string, string> };

/** How the browser should send the bytes (src/lib/upload-client.ts follows this). */
export function uploadTarget(fileId: string, key: string, mimeType: AllowedType): UploadTarget {
  if (usingBlob()) return { kind: 'blob', pathname: key, handleUploadUrl: '/api/files/blob', clientPayload: fileId, contentType: mimeType };
  if (process.env.NODE_ENV === 'production' && process.env.ALLOW_LOCAL_UPLOADS !== 'true') {
    throw new Error('File storage isn’t set up: connect a private Vercel Blob store (docs/DEPLOY.md).');
  }
  return { kind: 'local', url: `/api/files/upload/${fileId}?t=${encodeURIComponent(localUploadToken(fileId))}`, method: 'PUT', headers: { 'Content-Type': mimeType } };
}

/** Size of the stored object, or null if nothing was uploaded. */
export async function storedSize(key: string): Promise<number | null> {
  try {
    if (usingBlob()) return (await head(key)).size;
    return (await stat(localPath(key))).size;
  } catch {
    return null;
  }
}

/** The first bytes of the object, to check its real type. */
export async function readStart(key: string, n = 16): Promise<Uint8Array> {
  if (usingBlob()) {
    const res = await get(key, { access: 'private', useCache: false });
    if (!res || res.statusCode !== 200 || !res.stream) return new Uint8Array();
    const reader = res.stream.getReader();
    const chunks: Uint8Array[] = [];
    let total = 0;
    try {
      while (total < n) {
        const { done, value } = await reader.read();
        if (done || !value) break;
        chunks.push(value);
        total += value.byteLength;
      }
    } finally {
      await reader.cancel().catch(() => undefined);
    }
    const out = new Uint8Array(Math.min(n, total));
    let offset = 0;
    for (const c of chunks) {
      const take = c.subarray(0, out.length - offset);
      out.set(take, offset);
      offset += take.byteLength;
      if (offset >= out.length) break;
    }
    return out;
  }
  const fh = await open(localPath(key), 'r');
  try {
    const buf = Buffer.alloc(n);
    const { bytesRead } = await fh.read(buf, 0, n, 0);
    return new Uint8Array(buf.subarray(0, bytesRead));
  } finally {
    await fh.close();
  }
}

export async function removeObject(key: string) {
  try {
    if (usingBlob()) await del(key);
    else await rm(localPath(key), { force: true });
  } catch (e) {
    console.error('removeObject failed', key, e);
  }
}

/**
 * The bytes for a download. Blob: a stream from the private store (304 when the
 * browser's copy is current). Local: the file's bytes.
 */
export async function openForDownload(key: string, ifNoneMatch?: string | null) {
  if (usingBlob()) {
    const res = await get(key, { access: 'private', ifNoneMatch: ifNoneMatch ?? undefined });
    if (!res) return null;
    if (res.statusCode === 304) return { notModified: true as const, etag: res.blob.etag };
    return { notModified: false as const, body: res.stream as ReadableStream<Uint8Array>, etag: res.blob.etag as string | undefined };
  }
  try {
    // Same caching behaviour as Blob, so dev matches production. Files never change in place.
    const info = await stat(localPath(key));
    const etag = `"${info.size.toString(36)}-${Math.trunc(info.mtimeMs).toString(36)}"`;
    if (ifNoneMatch === etag) return { notModified: true as const, etag };
    return { notModified: false as const, body: new Uint8Array(await readLocal(key)) as Uint8Array | ReadableStream<Uint8Array>, etag: etag as string | undefined };
  } catch {
    return null;
  }
}

/** inline; filename="…" with a UTF-8 fallback, safe for any name. */
export function contentDisposition(filename: string) {
  const ascii = filename.replace(/[^\x20-\x7e]/g, '_').replace(/["\\]/g, '_');
  return `inline; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(filename)}`;
}

/** Does the file start the way its type says it should? */
export function matchesType(start: Uint8Array, mimeType: string) {
  const b = (i: number) => start[i];
  const ascii = (from: number, s: string) => [...s].every((ch, i) => b(from + i) === ch.charCodeAt(0));
  switch (mimeType) {
    case 'application/pdf':
      return ascii(0, '%PDF-');
    case 'image/png':
      return b(0) === 0x89 && ascii(1, 'PNG');
    case 'image/jpeg':
      return b(0) === 0xff && b(1) === 0xd8 && b(2) === 0xff;
    case 'image/webp':
      return ascii(0, 'RIFF') && ascii(8, 'WEBP');
    default:
      return false;
  }
}
